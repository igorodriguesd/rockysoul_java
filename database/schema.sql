CREATE TABLE USUARIO (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    PONTOS NUMBER DEFAULT 0 NOT NULL,
    NIVEL VARCHAR2(30) DEFAULT 'SEMENTE' NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_PONTOS CHECK (PONTOS >= 0)
);

CREATE TABLE ACAO_SUSTENTAVEL (
    ID_ACAO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    DESCRICAO VARCHAR2(300),
    PONTOS NUMBER NOT NULL,
    CONSTRAINT PK_ACAO PRIMARY KEY (ID_ACAO),
    CONSTRAINT CK_ACAO_PONTOS CHECK (PONTOS > 0)
);

CREATE TABLE REGISTRO_ACAO (
    ID_REGISTRO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    ID_ACAO NUMBER NOT NULL,
    DATA_REGISTRO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    PONTOS_OBTIDOS NUMBER NOT NULL,
    CONSTRAINT PK_REGISTRO PRIMARY KEY (ID_REGISTRO),
    CONSTRAINT FK_REGISTRO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_REGISTRO_ACAO FOREIGN KEY (ID_ACAO) REFERENCES ACAO_SUSTENTAVEL(ID_ACAO),
    CONSTRAINT CK_REGISTRO_PONTOS CHECK (PONTOS_OBTIDOS > 0)
);

CREATE TABLE RECOMPENSA (
    ID_RECOMPENSA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITULO VARCHAR2(120) NOT NULL,
    DESCRICAO VARCHAR2(300),
    CUSTO NUMBER NOT NULL,
    ESTOQUE NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_RECOMPENSA PRIMARY KEY (ID_RECOMPENSA),
    CONSTRAINT CK_RECOMPENSA_CUSTO CHECK (CUSTO > 0),
    CONSTRAINT CK_RECOMPENSA_ESTOQUE CHECK (ESTOQUE >= 0)
);

