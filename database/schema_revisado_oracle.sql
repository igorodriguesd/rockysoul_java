-- Oracle DDL + constraints das regras de negocio
-- Entidades: Usuario, Avatar, Historico, Missao, Selo,
--            Usuario_Missao (N:N) e Usuario_Selo (N:N)
--
-- ATENCAO: apenas estruturas (sem INSERT). A aplicacao cria e
-- manipula os dados pelo CRUD (camada DAO / service).
-- ============================================================

-- ---------- USUARIO ----------
CREATE TABLE USUARIO (
    ID_USUARIO    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NM_USUARIO    VARCHAR2(100)  NOT NULL,
    DS_EMAIL      VARCHAR2(150)  NOT NULL,
    NR_PONTOS     NUMBER         DEFAULT 0 NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT CK_USUARIO_PONTOS CHECK (NR_PONTOS >= 0)
);

-- ---------- AVATAR (1 usuario possui no maximo 1 avatar) ----------
CREATE TABLE AVATAR (
    ID_AVATAR     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO    NUMBER        NOT NULL,
    NM_AVATAR     VARCHAR2(60)  NOT NULL,
    DS_ESTILO     VARCHAR2(100),
    CONSTRAINT PK_AVATAR PRIMARY KEY (ID_AVATAR),
    CONSTRAINT UK_AVATAR_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT FK_AVATAR_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO)
);

-- ---------- HISTORICO (registro de acoes do usuario) ----------
CREATE TABLE HISTORICO (
    ID_HISTORICO  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO    NUMBER        NOT NULL,
    DS_ACAO       VARCHAR2(150) NOT NULL,
    NR_PONTOS     NUMBER(3)     NOT NULL,
    DT_ACAO       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HISTORICO PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_HISTORICO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT CK_HISTORICO_PONTOS CHECK (NR_PONTOS BETWEEN 0 AND 100)
);

-- ---------- MISSAO ----------
CREATE TABLE MISSAO (
    ID_MISSAO     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NM_MISSAO     VARCHAR2(100) NOT NULL,
    DS_MISSAO     VARCHAR2(300),
    NR_PONTOS     NUMBER(3)     NOT NULL,
    NR_NIVEL      NUMBER        NOT NULL,
    CONSTRAINT PK_MISSAO PRIMARY KEY (ID_MISSAO),
    CONSTRAINT CK_MISSAO_PONTOS CHECK (NR_PONTOS BETWEEN 0 AND 100),
    CONSTRAINT CK_MISSAO_NIVEL CHECK (NR_NIVEL > 0)
);

-- ---------- SELO ----------
CREATE TABLE SELO (
    ID_SELO          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NM_SELO          VARCHAR2(100) NOT NULL,
    DS_SELO          VARCHAR2(200),
    NR_PONTOS_MIN    NUMBER        DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SELO PRIMARY KEY (ID_SELO),
    CONSTRAINT CK_SELO_PONTOS_MIN CHECK (NR_PONTOS_MIN >= 0)
);

-- ---------- USUARIO_MISSAO (N:N com status e data de conclusao) ----------
CREATE TABLE USUARIO_MISSAO (
    ID_USUARIO    NUMBER       NOT NULL,
    ID_MISSAO     NUMBER       NOT NULL,
    DS_STATUS     VARCHAR2(20) NOT NULL,
    DT_CONCLUSAO  DATE,
    CONSTRAINT PK_USUARIO_MISSAO PRIMARY KEY (ID_USUARIO, ID_MISSAO),
    CONSTRAINT FK_UM_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_UM_MISSAO FOREIGN KEY (ID_MISSAO)
        REFERENCES MISSAO (ID_MISSAO),
    CONSTRAINT CK_UM_STATUS CHECK (DS_STATUS IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDA'))
);

-- ---------- USUARIO_SELO (N:N) ----------
CREATE TABLE USUARIO_SELO (
    ID_USUARIO    NUMBER NOT NULL,
    ID_SELO       NUMBER NOT NULL,
    DT_CONQUISTA  DATE   DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_USUARIO_SELO PRIMARY KEY (ID_USUARIO, ID_SELO),
    CONSTRAINT FK_US_SELO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_US_SELO_SELO FOREIGN KEY (ID_SELO)
        REFERENCES SELO (ID_SELO)
);